  Future<Map<String, int>> seedAll() async {
    dev.log(
      'Starting deterministic database seeding...',
      name: 'DatabaseSeeder',
    );

    return await db.transaction(() async {
      final counts = <String, int>{};

      // ─── PHASE 1: MASTER DATA ──────────────────────────────────────────────
      counts['users'] = await _seedUsers();
      counts['products'] = await _seedProducts();
      counts['vehicles'] = await _seedVehicles();
      counts['drivers'] = await _seedDrivers();
      counts['suppliers'] = await _seedSuppliers();
      counts['customers'] = await _seedCustomers();
      counts['customer_sites'] = await _seedCustomerSites();
      counts['customer_documents'] = await _seedCustomerDocuments();
      counts['storage_locations'] = await _seedStorageLocations();
      counts['ledger_accounts'] = await _seedLedgerAccounts();
      counts['app_settings'] = await _seedAppSettings();

      // ─── PHASE 2: PURCHASES ────────────────────────────────────────────────
      counts['fuel_purchases'] = await _seedPurchases();
      counts['fuel_purchase_items'] = await _seedPurchaseItems();

      // ─── PHASE 3: DELIVERIES & SALES INVOICES ─────────────────────────────
      counts['fuel_deliveries'] = await _seedDeliveries();
      counts['invoices'] = await _seedInvoices();
      counts['invoice_items'] = await _seedInvoiceItems();

      // ─── PHASE 4: PAYMENTS & EXPENSES ─────────────────────────────────────
      counts['payments'] = await _seedPayments();
      counts['payment_allocations'] = await _seedPaymentAllocations();
      counts['expenses'] = await _seedExpenses();

      // ─── PHASE 5: INVENTORY, LEDGER & AUDITS ──────────────────────────────
      counts['inventory_movements'] = await _seedInventoryMovements();
      counts['ledger_entries'] = await _seedLedgerEntries();
      counts['vehicle_service_records'] = await _seedVehicleServiceRecords();
      counts['stock_adjustments'] = await _seedStockAdjustments();
      counts['daily_stock_reconciliations'] = await _seedDailyReconciliations();
      counts['documents'] = await _seedDocuments();

      dev.log(
        'Seeding completed successfully: $counts',
        name: 'DatabaseSeeder',
      );
      return counts;
    });
  }

